  if (!secret || secret !== process.env.SEED_SECRET) {
    res.status(401).json({ message: "Non autorizzato" });
    return;
  }

  // Check if demo accounts already exist (by checking first admin email)
  const existing = await db
    .select()
    .from(usersTable)
